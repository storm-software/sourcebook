import { slug as toSlug } from "github-slugger";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, join, relative, resolve } from "node:path";
import ts from "typescript";
import { stringify } from "yaml";
import { DocumentationPageError } from "./errors.js";
import { collectFiles } from "./load.js";
import type { TSDocComment } from "./tsdoc.js";
import { parseTSDocComment, renderTSDocFeatures } from "./tsdoc.js";
import type { ComponentStory, ComponentStoryVariant } from "./types.js";

const GENERATED = "Generated by @sourcebook/core";
const STORY_FILE = /\.story\.[jt]sx?$/i;

function property(
  node: ts.Node | undefined,
  name: string
): ts.Expression | undefined {
  if (!node || !ts.isObjectLiteralExpression(node)) return undefined;
  for (const item of node.properties) {
    const key = item.name;
    if (!key || !(ts.isIdentifier(key) || ts.isStringLiteral(key))) continue;
    if (key.text !== name) continue;
    if (ts.isPropertyAssignment(item)) return item.initializer;
    if (ts.isShorthandPropertyAssignment(item)) return item.name;
  }
  return undefined;
}

/**
 * Split the TSDoc block above `node` into its summary and tags.
 * A tag starts a line outside a code fence, so `@` lines inside an example stay put.
 */
function readDocComment(file: ts.SourceFile, node: ts.Node): TSDocComment {
  const range = (
    ts.getLeadingCommentRanges(file.text, node.getFullStart()) ?? []
  )
    .filter(comment => file.text.startsWith("/**", comment.pos))
    .at(-1);

  return parseTSDocComment(range ? file.text.slice(range.pos, range.end) : "");
}

function readVariants(
  file: ts.SourceFile,
  args: ts.Expression | undefined
): ComponentStoryVariant[] {
  if (!args || !ts.isArrayLiteralExpression(args)) return [];

  return args.elements.flatMap(element => {
    const name = property(element, "variant");
    if (!name || !ts.isStringLiteralLike(name)) return [];
    const fixed = property(element, "fixed");

    return [
      fixed
        ? { name: name.text, fixed: fixed.getText(file) }
        : { name: name.text }
    ];
  });
}

/**
 * Read the first exported `defineStory()` call in a Fumadocs Story file.
 *
 * The TSDoc block above the export documents the component: its summary becomes the page description,
 * and `@anatomy`, `@usage`, `@remarks`, and `@example` become page sections.
 * Custom callouts and acknowledgements are rendered too. Other block tags are ignored.
 *
 * @param source - Story file source.
 * @param path - Story file path. The file name sets the slug and the script kind.
 * @returns The story. A story without a `Component` or a summary throws.
 */
export function parseComponentStory(
  source: string,
  path: string
): ComponentStory {
  const file = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true);

  for (const statement of file.statements) {
    if (
      !ts.isVariableStatement(statement) ||
      !statement.modifiers?.some(
        item => item.kind === ts.SyntaxKind.ExportKeyword
      )
    ) {
      continue;
    }

    for (const declaration of statement.declarationList.declarations) {
      const call = declaration.initializer;
      if (
        !ts.isIdentifier(declaration.name) ||
        !call ||
        !ts.isCallExpression(call) ||
        !ts.isIdentifier(call.expression) ||
        call.expression.text !== "defineStory"
      ) {
        continue;
      }

      const exportName = declaration.name.text;
      const options = call.arguments[0];
      const component = property(options, "Component");
      if (!component) {
        throw new DocumentationPageError(
          `Cannot read story ${path}: missing Component.\nComponent: pass the documented component to defineStory({ Component }).`,
          { path, missingFields: ["Component"] }
        );
      }

      const { summary, tags, callouts, acknowledgements } = readDocComment(
        file,
        statement
      );
      if (!summary) {
        throw new DocumentationPageError(
          `Cannot read story ${path}: missing description.\ndescription: write a TSDoc summary above \`export const ${exportName}\`. Its first paragraph is the page description.`,
          { path, missingFields: ["description"] }
        );
      }

      const tag = (name: string) =>
        tags.find(item => item.name === name)?.text || undefined;
      const anatomy = tag("anatomy");
      const usage = tag("usage");

      return {
        path,
        exportName,
        name: component.getText(file),
        slug: toSlug(basename(path).replace(STORY_FILE, "")) || exportName,
        description: (summary.split(/\n\s*\n/)[0] ?? "").replace(/\s+/g, " "),
        overview: summary,
        ...(anatomy ? { anatomy } : {}),
        ...(usage ? { usage } : {}),
        ...(tag("remarks") ? { remarks: tag("remarks") } : {}),
        ...(callouts.length ? { callouts } : {}),
        ...(acknowledgements.length ? { acknowledgements } : {}),
        examples: tags
          .filter(item => item.name === "example" && item.text)
          .map(item =>
            /^\s*(?:```|~~~)/m.test(item.text)
              ? item.text
              : `\`\`\`tsx\n${item.text}\n\`\`\``
          ),
        variants: readVariants(file, property(options, "args"))
      };
    }
  }

  throw new DocumentationPageError(
    `Cannot read story ${path}: no exported defineStory() call. Write \`export const story = defineStory({ Component })\`.`,
    { path }
  );
}

function inlineCode(source: string): string {
  const text = source.replace(/\s+/g, " ").trim();

  return text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``;
}

function frontmatter(title: string, description: string): string {
  return `---\n${stringify(
    { title, description, documentType: "reference" },
    { lineWidth: 0 }
  )}---`;
}

/**
 * Write the MDX page for one story. Fumadocs renders `<story.WithControl />` with live controls.
 *
 * @param story - Story from {@link parseComponentStory}.
 * @param storyPath - Import specifier for the story file, such as `../../src/callout.story.tsx` or `@ui/callout.story`. A `.js`, `.jsx`, `.ts`, or `.tsx` extension is dropped from the import.
 * @returns MDX with the front matter `@sourcebook/core` requires for a docs page.
 */
export function generateComponentStoryPage(
  story: ComponentStory,
  storyPath: string
): string {
  const section = (heading: string, body: string | undefined) =>
    body ? [`## ${heading}`, body] : [];
  const variants = story.variants
    .map(
      variant =>
        `- ${variant.name}${variant.fixed ? `: ${inlineCode(variant.fixed)}` : ""}`
    )
    .join("\n");

  return `${[
    frontmatter(story.name, story.description),
    `import { ${story.exportName} } from ${JSON.stringify(storyPath.replace(/\.[jt]sx?$/i, ""))};`,
    `{/* ${GENERATED} from ${storyPath}. Edit the story file, then generate the page again. */}`,
    `# ${story.name}`,
    story.overview,
    `<${story.exportName}.WithControl />`,
    ...section("Anatomy", story.anatomy),
    ...section("Usage", story.usage),
    ...section("Remarks", story.remarks),
    ...section("Variants", variants),
    ...section("Examples", story.examples.join("\n\n")),
    renderTSDocFeatures({
      callouts: story.callouts ?? [],
      acknowledgements: story.acknowledgements ?? []
    })
  ]
    .filter(Boolean)
    .join("\n\n")}\n`;
}

function generateCatalogIndex(
  stories: ComponentStory[],
  title: string
): string {
  const rows = stories.map(
    story =>
      `| [${story.name}](./${story.slug}.mdx) | ${story.description.replaceAll("|", "\\|")} |`
  );

  return `${[
    frontmatter(title, `${title} with live examples, anatomy, and usage.`),
    `{/* ${GENERATED}. Edit the story files, then generate the catalog again. */}`,
    `# ${title}`,
    ["| Name | Description |", "| --- | --- |", ...rows].join("\n")
  ].join("\n\n")}\n`;
}

/**
 * Map a story file to a `paths` alias from a tsconfig, so a page outside the story's package imports it
 * the way the docs app resolves modules. The alias with the longest matching target wins.
 */
function tsconfigAlias(
  configPath: string | undefined
): (file: string) => string | undefined {
  if (!configPath) return () => undefined;
  const parsed = ts.getParsedCommandLineOfConfigFile(
    configPath,
    {},
    {
      ...ts.sys,
      readDirectory: () => [],
      onUnRecoverableConfigFileDiagnostic: () => {}
    }
  );
  const {
    paths = {},
    baseUrl,
    pathsBasePath
  } = (parsed?.options ?? {}) as ts.CompilerOptions & {
    pathsBasePath?: string;
  };
  const base = baseUrl ?? pathsBasePath ?? dirname(configPath);

  return file => {
    let best: { length: number; specifier: string } | undefined;
    for (const [alias, targets] of Object.entries(paths)) {
      const [aliasPrefix = "", aliasSuffix = ""] = alias.split("*");
      for (const target of targets) {
        const wildcard = target.includes("*");
        if (wildcard !== alias.includes("*")) continue;
        const [prefix = "", suffix = ""] = resolve(base, target).split("*");
        const match = wildcard
          ? file.length >= prefix.length + suffix.length &&
            file.startsWith(prefix) &&
            file.endsWith(suffix)
          : file === prefix || file.replace(/\.[jt]sx?$/i, "") === prefix;
        if (!match || (best && best.length >= prefix.length)) continue;
        best = {
          length: prefix.length,
          specifier: wildcard
            ? `${aliasPrefix}${file.slice(prefix.length, file.length - suffix.length).replaceAll("\\", "/")}${aliasSuffix}`
            : alias
        };
      }
    }
    return best?.specifier;
  };
}

async function assertGenerated(target: string): Promise<void> {
  const existing = await readFile(target, "utf8").catch(() => undefined);
  if (existing !== undefined && !existing.includes(GENERATED)) {
    throw new DocumentationPageError(
      `Cannot write the component catalog: ${target} was not generated by @sourcebook/core. Move its content into the story's TSDoc, then delete it.`,
      { path: target }
    );
  }
}

/**
 * Generate a component catalog from every `*.story.{js,jsx,ts,tsx}` file under `sources`.
 * Writes one `<slug>.mdx` page per story and an `index.mdx` table of them.
 * Hidden entries and dependency or build directories are skipped.
 *
 * A page is replaced only when `@sourcebook/core` generated it. A hand-written `<slug>.md`,
 * `<slug>.mdx`, `index.md`, or `index.mdx` in `outputDirectory` throws before any file is written.
 *
 * Each page imports its story through a `paths` alias when the tsconfig maps one to the story file,
 * for example `@ui/button/button.story` for `"@ui/*": ["../../packages/ui/src/*"]`.
 * Otherwise the import is relative to `outputDirectory`.
 *
 * @param sources - Directories to search for story files.
 * @param outputDirectory - Directory for the MDX pages.
 * @param options - `title` names the catalog page and defaults to `Components`.
 * `tsconfig` is the docs app's tsconfig for import aliases. It defaults to the nearest `tsconfig.json` at or above `outputDirectory`.
 * @returns Paths of the written pages, with `index.mdx` last.
 */
export async function writeComponentCatalog(
  sources: string | string[],
  outputDirectory: string,
  options: { title?: string; tsconfig?: string } = {}
): Promise<string[]> {
  const files = (
    await Promise.all(
      [sources].flat().map(async source => collectFiles(source, STORY_FILE))
    )
  )
    .flat()
    .sort((left, right) => left.localeCompare(right));
  if (!files.length) {
    throw new DocumentationPageError(
      `Cannot write the component catalog: no *.story.{js,jsx,ts,tsx} files in ${[sources].flat().join(", ")}.`
    );
  }

  const stories = new Map<string, ComponentStory>();
  for (const file of files) {
    const story = parseComponentStory(await readFile(file, "utf8"), file);
    const existing = stories.get(story.slug);
    if (existing || story.slug === "index") {
      throw new DocumentationPageError(
        `Cannot write the component catalog: ${existing?.path ?? "the catalog"} and ${file} both write ${story.slug}.mdx. Rename one file.`,
        { path: file }
      );
    }
    stories.set(story.slug, story);
  }

  const alias = tsconfigAlias(
    options.tsconfig ??
      ts.findConfigFile(resolve(outputDirectory), path =>
        ts.sys.fileExists(path)
      )
  );
  const pages = [...stories.values()].map(story => {
    const file = resolve(story.path);
    const path = relative(outputDirectory, file).replaceAll("\\", "/");

    return {
      target: join(outputDirectory, `${story.slug}.mdx`),
      content: generateComponentStoryPage(
        story,
        alias(file) ?? (path.startsWith("../") ? path : `./${path}`)
      )
    };
  });
  pages.push({
    target: join(outputDirectory, "index.mdx"),
    content: generateCatalogIndex(
      [...stories.values()].sort((left, right) =>
        left.name.localeCompare(right.name)
      ),
      options.title ?? "Components"
    )
  });

  for (const { target } of pages) {
    await assertGenerated(target);
    await assertGenerated(target.replace(/x$/, ""));
  }
  await mkdir(outputDirectory, { recursive: true });
  for (const { target, content } of pages) await writeFile(target, content);

  return pages.map(page => page.target);
}
